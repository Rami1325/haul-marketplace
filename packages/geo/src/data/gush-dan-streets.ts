import type { LatLng } from '@haul/types';

/**
 * ---------------------------------------------------------------------------
 * Seed streets — real Gush Dan, approximate geometry
 * ---------------------------------------------------------------------------
 * The streets and the cities are real. The geometry is not survey data: each
 * entry is a street midpoint good to a few hundred metres, a compass bearing,
 * and a length, from which the fake provider interpolates a house number's
 * position. That is enough to develop and test a booking flow against —
 * suggestions rank sensibly, inter-city legs are plausibly long, and central
 * Tel Aviv addresses sit close enough together to exercise the short-hop cases.
 * It is not enough to navigate by, and nothing here should ever reach a driver.
 *
 * Postal codes are synthetic. Only the leading digits reflect the real Israeli
 * scheme (6xxxxxx Tel Aviv, 52xxxxx Ramat Gan, and so on); the rest is derived
 * from a hash so the fake can populate a field the schema asks for. A synthetic
 * מיקוד on a real envelope is a returned envelope — see `FakeGeoProvider`.
 *
 * Coverage is deliberately Gush Dan only. The launch geography is three
 * postcodes in central Tel Aviv, and a fake that cheerfully geocodes Eilat
 * would let an out-of-area bug reach production untested.
 * ---------------------------------------------------------------------------
 */

export interface SeedStreet {
  id: string;
  /** רחוב, as signposted. */
  nameHe: string;
  /** The Latin transliteration on the same sign. Israeli signs carry both. */
  nameEn: string;
  cityHe: string;
  cityEn: string;
  /** First three digits of the מיקוד. Real; the remaining four are synthesised. */
  postalPrefix: string;
  /** Roughly the middle of the street. */
  centre: LatLng;
  /** Degrees from north, in the direction house numbers increase. */
  bearingDeg: number;
  lengthMeters: number;
  /** The range of house numbers the fake will admit exists. */
  minNumber: number;
  maxNumber: number;
}

